from __future__ import annotations

from typing import Any, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.schemas.f01_schemas import CitationDto


def format_chunk_citation_key(document_code: str, version: str, section_index: int) -> str:
    """Canonical chunk citation key shared by ToolGateway observations and BoundedAgentRunner."""
    return f"{document_code}@{version}#{int(section_index)}"


class AgentRunBinding(BaseModel):
    model_config = ConfigDict(extra="forbid")

    runId: UUID
    correlationId: UUID
    actorId: UUID
    actorRole: Literal["STUDENT", "TRAINER", "ADMIN"]
    subjectId: UUID | None = None
    coachingMode: Literal["SELF_DIRECTED", "HUMAN_COACH"] | None = None
    allowedActions: list[str] = Field(default_factory=list)
    allowedSourceIds: list[str] = Field(default_factory=list)


class ConversationMessageDto(BaseModel):
    model_config = ConfigDict(extra="forbid")

    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=4000)


class AgentTurnRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    binding: AgentRunBinding
    message: str = Field(min_length=1, max_length=2000)
    language: str = "vi"
    conversationHistory: list[ConversationMessageDto] = Field(default_factory=list, max_length=20)
    maxModelTurns: int = Field(default=5, ge=1, le=8)
    maxToolCalls: int = Field(default=8, ge=1, le=12)
    maxSearchCalls: int = Field(default=2, ge=1, le=4)
    deadlineSeconds: float = Field(default=25.0, ge=1.0, le=60.0)


class ToolCallRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    toolName: str = Field(min_length=1, max_length=64)
    arguments: dict[str, Any] = Field(default_factory=dict)


class ToolObservation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    toolName: str
    status: Literal["OK", "DENIED", "NOT_FOUND", "UNKNOWN_DATA", "ERROR", "REJECTED_REPEAT"]
    summary: str
    data: dict[str, Any] = Field(default_factory=dict)
    sourceRefs: list[str] = Field(default_factory=list)


class AgentStepTrace(BaseModel):
    model_config = ConfigDict(extra="forbid")

    step: int
    action: Literal["MODEL_DECISION", "TOOL_CALL", "CLARIFICATION", "FINAL_ANSWER", "STOPPED"]
    toolName: str | None = None
    status: str
    durationMs: int = 0
    sourceRefs: list[str] = Field(default_factory=list)


class ProposedActionDraft(BaseModel):
    model_config = ConfigDict(extra="forbid")

    proposalType: Literal["F03_WORKOUT_ADJUSTMENT", "F05_WORKOUT_RESCHEDULE"]
    recommendationId: UUID | None = None
    status: str = "PENDING"
    summary: str
    payload: dict[str, Any] = Field(default_factory=dict)


class AgentTurnResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    runId: UUID
    correlationId: UUID
    runStatus: Literal["SUCCEEDED", "FAILED", "REJECTED_BY_VALIDATOR", "CANCELLED"]
    resultType: Literal["INFORMATION", "CLARIFICATION_REQUIRED", "PROPOSAL_DRAFT", "INSUFFICIENT_DATA", "BLOCKED"]
    reasonCode: str = "NONE"
    answer: str = ""
    clarificationQuestion: str | None = None
    citations: list[CitationDto] = Field(default_factory=list)
    # Runner-owned IDs of chunks exposed as observations, never generated by the model.
    evidenceChunkIds: list[str] = Field(default_factory=list, max_length=40)
    limitations: list[str] = Field(default_factory=list)
    missingData: list[str] = Field(default_factory=list)
    proposalDraft: ProposedActionDraft | None = None
    stopReason: str
    promptVersion: str
    model: str
    provider: str
    steps: list[AgentStepTrace] = Field(default_factory=list)
