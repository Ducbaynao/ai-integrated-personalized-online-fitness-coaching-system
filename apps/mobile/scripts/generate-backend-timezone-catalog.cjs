#!/usr/bin/env node
/*
 * Generates src/features/shared/backendTimezoneCatalog.ts from the Backend's exact
 * timezone membership rule: java.time.ZoneId.getAvailableZoneIds().
 *
 * Usage (from apps/mobile, with the JDK matching the Backend runtime on PATH):
 *   node scripts/generate-backend-timezone-catalog.cjs          # regenerate
 *   node scripts/generate-backend-timezone-catalog.cjs --check  # compare only, exit 1 on drift
 *
 * Only the Java standard library runs; no Spring, Docker, database or network access.
 */
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const mobileRoot = path.resolve(__dirname, '..');
const javaDir = path.join(__dirname, 'timezone-catalog');
const outputFile = path.join(mobileRoot, 'src', 'features', 'shared', 'backendTimezoneCatalog.ts');
const checkOnly = process.argv.includes('--check');

// Relative source name + cwd: the Java launcher mis-decodes non-ASCII absolute paths on Windows.
const raw = execFileSync('java', ['BackendZoneIds.java'], { cwd: javaDir, encoding: 'utf8' });
const meta = {};
const ids = [];
for (const line of raw.split(/\r?\n/)) {
  if (!line) continue;
  if (line.startsWith('#')) {
    const [key, ...rest] = line.slice(1).split('=');
    meta[key] = rest.join('=');
  } else {
    ids.push(line);
  }
}
if (!meta.runtime || !meta.tzdb || ids.length === 0) {
  console.error('Unexpected Java output; catalog not written.');
  process.exit(2);
}

const content = `// GENERATED by scripts/generate-backend-timezone-catalog.cjs. Do not edit by hand.
// Source: java.time.ZoneId.getAvailableZoneIds(), the exact membership set checked by the
// Backend timezone validators (for example NutritionBasicService.zone and
// NutritionTargetDayService.validZone). Regenerate or verify with the JDK matching the
// Backend runtime: \`node scripts/generate-backend-timezone-catalog.cjs [--check]\`.
export const BACKEND_TIMEZONE_CATALOG_SOURCE = {
  javaRuntime: ${JSON.stringify(meta.runtime)},
  javaVendor: ${JSON.stringify(meta.vendor ?? '')},
  tzdbVersion: ${JSON.stringify(meta.tzdb)},
  count: ${ids.length},
} as const;

export const BACKEND_ZONE_IDS: readonly string[] = [
${ids.map((id) => `  ${JSON.stringify(id)},`).join('\n')}
];
`;

if (checkOnly) {
  const existing = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8').replace(/\r\n/g, '\n') : '';
  if (existing !== content) {
    console.error(`Backend timezone catalog drift: ${path.relative(mobileRoot, outputFile)} does not match ` +
      `Java ${meta.runtime} (tzdb ${meta.tzdb}, ${ids.length} IDs).`);
    process.exit(1);
  }
  console.log(`Backend timezone catalog matches Java ${meta.runtime} (${meta.vendor}), tzdb ${meta.tzdb}, ${ids.length} IDs.`);
} else {
  fs.writeFileSync(outputFile, content);
  console.log(`Wrote ${ids.length} IDs from Java ${meta.runtime} (${meta.vendor}), tzdb ${meta.tzdb}.`);
}
